CREATE OR REPLACE FUNCTION public.grant_purchased_render_credits(
  p_user_id UUID,
  p_checkout_session_id TEXT,
  p_pack_id TEXT,
  p_credits BIGINT,
  p_price_id TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  inserted INTEGER;
BEGIN
  IF p_user_id IS NULL OR p_checkout_session_id IS NULL OR length(p_checkout_session_id) < 5
     OR p_pack_id IS NULL OR p_credits <= 0 OR p_price_id IS NULL THEN
    RAISE EXCEPTION 'Invalid render credit grant';
  END IF;

  INSERT INTO public.render_credit_purchase_events(
    stripe_checkout_session_id, user_id, pack_id, credits, stripe_price_id
  )
  VALUES (p_checkout_session_id, p_user_id, p_pack_id, p_credits, p_price_id)
  ON CONFLICT (stripe_checkout_session_id) DO NOTHING;

  GET DIAGNOSTICS inserted = ROW_COUNT;
  IF inserted = 0 THEN RETURN false; END IF;

  INSERT INTO public.user_token_balances(user_id, purchased_tokens, purchased_render_credits, updated_at)
  VALUES (p_user_id, 0, p_credits, now())
  ON CONFLICT (user_id)
  DO UPDATE SET
    purchased_render_credits = public.user_token_balances.purchased_render_credits + EXCLUDED.purchased_render_credits,
    updated_at = now();

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.grant_purchased_render_credits(UUID,TEXT,TEXT,BIGINT,TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.grant_purchased_render_credits(UUID,TEXT,TEXT,BIGINT,TEXT)
  TO service_role;

CREATE OR REPLACE FUNCTION public.get_cross_repo_usage_summary(p_user_id UUID)
RETURNS JSON
LANGUAGE SQL
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT json_build_object(
    'period_start', date_trunc('month', now() AT TIME ZONE 'UTC')::date,
    'ai_tokens_used', COALESCE(SUM(units) FILTER (WHERE feature='ai_tokens'),0),
    'api_requests_used', COALESCE(SUM(units) FILTER (WHERE feature='ai_requests'),0),
    'render_credits_used', COALESCE(SUM(units) FILTER (WHERE feature='render_credits'),0),
    'by_source', COALESCE((
      SELECT json_object_agg(source, payload)
      FROM (
        SELECT source, json_build_object(
          'ai_tokens', COALESCE(SUM(units) FILTER (WHERE feature='ai_tokens'),0),
          'api_requests', COALESCE(SUM(units) FILTER (WHERE feature='ai_requests'),0),
          'render_credits', COALESCE(SUM(units) FILTER (WHERE feature='render_credits'),0)
        ) payload
        FROM public.cross_repo_usage_events e2
        WHERE e2.user_id=p_user_id
          AND e2.period_start=date_trunc('month', now() AT TIME ZONE 'UTC')::date
        GROUP BY source
      ) source_totals
    ), '{}'::json)
  )
  FROM public.cross_repo_usage_events e
  WHERE e.user_id=p_user_id
    AND e.period_start=date_trunc('month', now() AT TIME ZONE 'UTC')::date;
$$;

REVOKE ALL ON FUNCTION public.get_cross_repo_usage_summary(UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_cross_repo_usage_summary(UUID) TO service_role;


CREATE OR REPLACE FUNCTION public.get_usage_totals_for_alerts(p_user_id UUID)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
DECLARE
  v_period_start DATE := date_trunc('month', now() AT TIME ZONE 'UTC')::date;
  plan_name TEXT := 'free';
  result JSON;
BEGIN
  SELECT COALESCE(s.plan, 'free') INTO plan_name
  FROM public.subscriptions s
  WHERE s.user_id = p_user_id AND s.status IN ('active','trialing')
  ORDER BY s.updated_at DESC
  LIMIT 1;

  SELECT json_build_object(
    'plan', COALESCE(plan_name, 'free'),
    'period_start', v_period_start,
    'api_requests', COALESCE((
      SELECT units FROM public.billable_usage_counters
      WHERE user_id=p_user_id AND period_start=v_period_start AND feature='ai_requests'
    ),0),
    'ai_tokens', COALESCE((
      SELECT units FROM public.billable_usage_counters
      WHERE user_id=p_user_id AND period_start=v_period_start AND feature='ai_tokens'
    ),0),
    'three_d_generations', COALESCE((
      SELECT units FROM public.billable_usage_counters
      WHERE user_id=p_user_id AND period_start=v_period_start AND feature='render_credits'
    ),0),
    'storage', COALESCE((
      SELECT SUM(storage_used) FROM public.projects
      WHERE owner_id=p_user_id AND status <> 'deleted'
    ),0)
  ) INTO result;

  RETURN result;
END $$;

REVOKE ALL ON FUNCTION public.get_usage_totals_for_alerts(UUID) FROM PUBLIC, authenticated;
GRANT EXECUTE ON FUNCTION public.get_usage_totals_for_alerts(UUID) TO service_role;
